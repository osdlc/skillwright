/// The provenance marker every `SKILL.md` and command a built marketplace
/// emits opens its body with. `check` reads it back to tell a tree this tool
/// built from one somebody wrote.
pub const GENERATED_MARKER: &str = "<!-- Generated by skillwright from ";

/// Where the per-skill `scripts/sdlc` shim lands, relative to a skill's own
/// directory — and the text a [`CliInvocation::SkillRelativeShim`] harness
/// writes a CLI call site as. One constant for both, so the file and the path
/// a body names cannot drift apart.
pub const SHIM_RELATIVE_PATH: &str = "scripts/sdlc";

/// What a translator returns: every file, by path.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct FileTree {
    /// Forward-slashed paths, relative to the directory the tree is emitted
    /// into, to their content.
    pub files: BTreeMap<String, TreeFile>,
    /// `sw-overrides` keys that changed nothing — a diagnostic, never a
    /// refusal.
    pub redundant_overrides: Vec<RedundantOverride>,
}

/// One file of a [`FileTree`].
#[derive(Debug, Clone, PartialEq)]
pub struct TreeFile {
    /// The bytes.
    pub bytes: Vec<u8>,
    /// Whether the file is executable.
    pub executable: bool,
    /// The note the file came from and what fed it, where a destination's
    /// manifest records one.
    pub source: Option<FileSource>,
}

/// What one emitted file was built from.
#[derive(Debug, Clone, PartialEq)]
pub struct FileSource {
    /// The note that owns the file, vault-relative.
    pub note: String,
    /// Every note, unresolved name and call that fed it.
    pub closure: Closure,
}

impl FileTree {
    /// Adds a file, replacing one already at `path` — the order a pack is
    /// written in decides, the same as writes landing on one directory.
    pub fn insert(&mut self, path: &str, bytes: Vec<u8>, executable: bool) {
        self.insert_from(path, bytes, executable, None);
    }

    fn insert_from(
        &mut self,
        path: &str,
        bytes: Vec<u8>,
        executable: bool,
        source: Option<FileSource>,
    ) {
        self.files.insert(
            crate::skill::forward_slashed(Path::new(path)),
            TreeFile {
                bytes,
                executable,
                source,
            },
        );
    }

    /// The files as a projection's list, in path order.
    pub fn projected(&self) -> Vec<ProjectedFile> {
        self.files
            .iter()
            .map(|(path, file)| ProjectedFile {
                relative_path: path.clone(),
                content: file.bytes.clone(),
                executable: file.executable,
            })
            .collect()
    }
}

/// Where a pack is written.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Layout {
    /// A built marketplace: packs under the harness's own tree, beside its
    /// marketplace manifest, every emitted body marked as generated.
    Marketplace,
    /// A destination: the pack in the harness's skills directory.
    Destination,
}

/// One harness's way of writing the marketplace model.
pub trait HarnessTranslator: Sync {
    /// The harness's row.
    fn profile(&self) -> &'static HarnessProfile;

    /// The harness's plugin format. Only a harness with one has a translator
    /// that writes packs.
    fn format(&self) -> &'static PluginFormat {
        self.profile().format()
    }

    /// Does this member publish here? Its kind has a place in the pack, and
    /// its `sw-targets` names this harness.
    fn admits(&self, component: &Component) -> bool {
        admits(&component.discovered, self.profile())
    }

    /// The name a skill of `plugin` publishes under: its directory, its
    /// frontmatter `name`, and the name a call to it renders.
    ///
    /// # Errors
    ///
    /// `refused: published-name-invalid` — a prefixed name the Agent Skills
    /// spec does not admit.
    fn published_name(&self, plugin: &str, skill: &str) -> Result<String, CoreError> {
        crate::export::published_skill_name(naming(self.profile()), plugin, skill)
    }

    /// A call, as this harness invokes the skill it names.
    ///
    /// # Errors
    ///
    /// `refused: skill-call-not-shipped` when this harness does not ship the
    /// skill, and what the runtime refuses about the name.
    fn render_call(&self, call: &Call) -> Result<String, CoreError> {
        let profile = self.profile();
        render_call(
            call,
            profile.name,
            Some(profile.declaration),
            naming(profile),
        )
    }

    /// A resolved body as this harness reads it, and whether it called the
    /// plugin's CLI through the skill-relative shim.
    ///
    /// # Errors
    ///
    /// What [`Self::render_call`] refuses.
    fn render_body(&self, body: &Body) -> Result<(String, bool), CoreError> {
        let cli = self
            .profile()
            .plugin
            .as_ref()
            .map_or(CliInvocation::PluginRootToken, |f| f.cli_invocation);
        write_body(body, cli, |call| self.render_call(call))
    }

    /// The plugin's hooks file and its gap report, written into `tree` under
    /// `base`. Returns whether a hooks file was written.
    ///
    /// A hook note this harness cannot carry stops the build, rather than
    /// writing a partial hooks file — unless the note has no `sw-targets` and
    /// another harness carries it, when it is left off here the way
    /// `sw-targets` would narrow it. A canonical file's uncarried hooks are
    /// not a refusal; the gap report says where each went.
    ///
    /// # Errors
    ///
    /// Everything [`to_adapt_hook`] and [`project_plugin_hooks`] refuse.
    fn hooks(
        &self,
        plugin: &Plugin,
        hooks: &[&Component],
        base: &str,
        tree: &mut FileTree,
    ) -> Result<bool, CoreError> {
        default_hooks(self.profile(), plugin, hooks, base, tree)
    }

    /// The pack manifest, `skills` the names of the skills this harness
    /// carries from the plugin.
    fn plugin_manifest(
        &self,
        plugin: &str,
        skills: &[&str],
        config: &MarketplaceConfig,
        wrote_hooks: bool,
    ) -> String {
        let format = self.format();
        let hooks = format.hooks_manifest_entry.filter(|_| wrote_hooks);
        render_plugin_manifest(format.dialect, plugin, skills, config, hooks)
    }

    /// The marketplace manifest listing `listed` — each carried plugin and
    /// its carried skills' names. `None` for a harness with no marketplace.
    fn marketplace_manifest(
        &self,
        _listed: &[(&str, Vec<&str>)],
        _name: &str,
        _config: &MarketplaceConfig,
    ) -> Option<String> {
        None
    }

    /// The whole marketplace as this harness's tree, paths relative to the
    /// marketplace directory.
    ///
    /// # Errors
    ///
    /// What writing any member refuses.
    fn translate(&self, market: &Marketplace, ns: &Namespace) -> Result<FileTree, CoreError> {
        let format = self.format();
        let mut tree = FileTree::default();
        let mut listed: Vec<(&str, Vec<&str>)> = Vec::new();
        for (name, plugin) in &market.plugins {
            let Some(skills) = self.write_pack(
                plugin,
                &market.config,
                &format!("{}/{name}", format.packs),
                Layout::Marketplace,
                ns,
                &mut tree,
            )?
            else {
                continue;
            };
            listed.push((name, skills));
        }
        if let Some(path) = format.marketplace_manifest
            && let Some(manifest) = self.marketplace_manifest(&listed, &market.name, &market.config)
        {
            tree.insert(path, manifest.into_bytes(), false);
        }
        Ok(tree)
    }

    /// One plugin as a pack at a destination, paths relative to the
    /// destination root.
    ///
    /// # Errors
    ///
    /// What writing any member refuses.
    fn translate_pack(&self, pack: &Pack, ns: &Namespace) -> Result<FileTree, CoreError> {
        let mut tree = FileTree::default();
        let base = format!("{}/{}", self.format().skills_dir, pack.plugin.name);
        self.write_pack(
            &pack.plugin,
            &pack.config,
            &base,
            Layout::Destination,
            ns,
            &mut tree,
        )?;
        Ok(tree)
    }

    /// One note published on its own, paths relative to the destination root.
    ///
    /// # Errors
    ///
    /// What the runtime's renderer refuses.
    fn translate_component(
        &self,
        component: &Component,
        ns: &Namespace,
    ) -> Result<FileTree, CoreError> {
        let profile = self.profile();
        write_component(
            component,
            &Destination {
                canonical: profile.name,
                runtime: profile.runtime,
                calls: Some(profile.declaration),
            },
            ns,
        )
    }

    /// One plugin's pack into `tree` under `base`: its skills, its commands
    /// where the pack has a place for one, its hooks, its assets and its
    /// manifest. Returns the carried skills' names, or `None` when this
    /// harness carries nothing of the plugin — a plugin whose every member is
    /// narrowed away is absent entirely: no directory, no manifest, no
    /// listing.
    ///
    /// # Errors
    ///
    /// What writing any member refuses.
    fn write_pack<'p>(
        &self,
        plugin: &'p Plugin,
        config: &MarketplaceConfig,
        base: &str,
        layout: Layout,
        ns: &Namespace,
        tree: &mut FileTree,
    ) -> Result<Option<Vec<&'p str>>, CoreError> {
        let skills: Vec<&Component> = plugin.skills.iter().filter(|c| self.admits(c)).collect();
        let commands: Vec<&Component> = plugin.commands.iter().filter(|c| self.admits(c)).collect();
        let hooks: Vec<&Component> = plugin.hooks.iter().filter(|c| self.admits(c)).collect();
        if skills.is_empty() && commands.is_empty() && hooks.is_empty() {
            return Ok(None);
        }
        let siblings: BTreeSet<&str> = plugin.skills.iter().map(|s| s.name.as_str()).collect();
        for skill in &skills {
            self.write_pack_skill(plugin, skill, &siblings, base, layout, ns, tree)?;
        }
        for command in &commands {
            self.write_pack_command(command, base, layout, ns, tree)?;
        }
        let wrote_hooks = self.hooks(plugin, &hooks, base, tree)?;
        for asset in &plugin.assets {
            tree.insert(
                &format!("{base}/{}", asset.dest),
                asset.bytes.clone(),
                asset.executable,
            );
        }
        let names: Vec<&str> = skills.iter().map(|s| s.name.as_str()).collect();
        let manifest = self.plugin_manifest(&plugin.name, &names, config, wrote_hooks);
        tree.insert(
            &format!("{base}/{}", self.format().plugin_manifest),
            manifest.into_bytes(),
            false,
        );
        Ok(Some(names))
    }

    /// One skill into a pack, at `<base>/skills/<published name>/`.
    ///
    /// # Errors
    ///
    /// `refused: published-name-invalid`, and what rendering refuses.
    #[allow(clippy::too_many_arguments)]
    fn write_pack_skill(
        &self,
        plugin: &Plugin,
        skill: &Component,
        siblings: &BTreeSet<&str>,
        base: &str,
        layout: Layout,
        ns: &Namespace,
        tree: &mut FileTree,
    ) -> Result<(), CoreError> {
        let profile = self.profile();
        let format = self.format();
        let published = self.published_name(&plugin.name, &skill.name)?;
        let (mut projection, used_shim) = projection_of(skill, |body| self.render_body(body))?;
        projection.content.name = published.clone();
        if format.naming == SkillNaming::PluginPrefixed {
            projection.content.body =
                rewrite_sibling_paths(&projection.content.body, &plugin.name, siblings);
        }
        if layout == Layout::Marketplace {
            mark_generated(&mut projection, &skill.path);
        }
        let (files, redundant) = project_skill_reporting(
            &projection,
            &[profile.runtime.to_owned()],
            ns,
            Some(profile.name),
        )?;
        tree.redundant_overrides.extend(redundant);
        let strip = format!("{}/{published}/", format.skills_dir);
        let closures = &skill
            .resolved
            .as_ref()
            .expect("an admitted skill is resolved")
            .closures;
        for file in files {
            let relative = file.relative_path.strip_prefix(&strip).ok_or_else(|| {
                CoreError::Projection(format!(
                    "{}: `{}` did not land under `{strip}` — the {} projection moved its layout",
                    skill.name, file.relative_path, profile.runtime
                ))
            })?;
            // The entry's closure is keyed by the name a skill's own output
            // has, which is what `relative` is for its `SKILL.md`.
            let source = closures
                .get(relative)
                .or_else(|| closures.get("SKILL.md"))
                .map(|closure| FileSource {
                    note: skill.path.clone(),
                    closure: closure.clone(),
                });
            tree.insert_from(
                &format!("{base}/skills/{published}/{relative}"),
                file.content,
                file.executable,
                source,
            );
        }
        // Only where a CLI call site was actually rewritten: a harness that
        // substitutes `${CLAUDE_PLUGIN_ROOT}` itself never needs the shim,
        // and a skill whose body never called the CLI has nothing pointing at
        // it.
        if used_shim && let Some(target) = &plugin.shim_target {
            tree.insert(
                &format!("{base}/skills/{published}/{SHIM_RELATIVE_PATH}"),
                sdlc_shim_script(target).into_bytes(),
                true,
            );
        }
        Ok(())
    }

    /// One command into a pack, at `<base>/commands/<name>.<ext>`. Called
    /// only where the pack has a place for one.
    ///
    /// # Errors
    ///
    /// What rendering refuses.
    fn write_pack_command(
        &self,
        command: &Component,
        base: &str,
        layout: Layout,
        ns: &Namespace,
        tree: &mut FileTree,
    ) -> Result<(), CoreError> {
        let profile = self.profile();
        let (mut projection, _) = projection_of(command, |body| self.render_body(body))?;
        if layout == Layout::Marketplace {
            mark_generated(&mut projection, &command.path);
        }
        // A command projects to exactly one file, so the file's own name is
        // all that travels onto `commands/`.
        let files = project_command(
            &projection,
            &[profile.runtime.to_owned()],
            ns,
            Some(profile.name),
        )?;
        let closures = &command
            .resolved
            .as_ref()
            .expect("an admitted command is resolved")
            .closures;
        for file in files {
            let filename = Path::new(&file.relative_path).file_name().ok_or_else(|| {
                CoreError::Projection(format!(
                    "{}: `{}` names no file — the {} projection moved its layout",
                    command.name, file.relative_path, profile.runtime
                ))
            })?;
            let source = closures.get("SKILL.md").map(|closure| FileSource {
                note: command.path.clone(),
                closure: closure.clone(),
            });
            tree.insert_from(
                &format!("{base}/commands/{}", filename.to_string_lossy()),
                file.content,
                file.executable,
                source,
            );
        }
        Ok(())
    }
}

/// A destination a single note is published to, named by any spelling — a
/// harness's row, or a runtime name no row holds, which renders through as
/// given.
#[derive(Debug, Clone, Copy)]
pub struct Destination<'a> {
    /// The canonical name, or the name as requested when no row holds it.
    pub canonical: &'a str,
    /// The runtime the note renders through.
    pub runtime: &'a str,
    /// The runtime whose syntax a call is written in. `None` writes a call as
    /// the skill's bare name.
    pub calls: Option<RuntimeId>,
}

/// One note on its own at `destination`, through the renderer for its kind.
///
/// # Errors
///
/// What the runtime's renderer refuses, and what writing a call refuses.
pub fn write_component(
    component: &Component,
    destination: &Destination<'_>,
    ns: &Namespace,
) -> Result<FileTree, CoreError> {
    let (projection, _) = projection_of(component, |body| {
        // A skill published on its own has no plugin, so a call to another
        // skill is the runtime's form without a namespace.
        write_body(body, CliInvocation::PluginRootToken, |call| {
            render_call(
                call,
                destination.canonical,
                destination.calls,
                SkillNaming::Bare,
            )
        })
    })?;
    let runtime = [destination.runtime.to_owned()];
    let mut tree = FileTree::default();
    let files = match component.kind {
        EntityKind::Command => {
            project_command(&projection, &runtime, ns, Some(destination.canonical))?
        }
        EntityKind::Agent => project_agent(&projection, &runtime, ns)?,
        _ => {
            let (files, redundant) =
                project_skill_reporting(&projection, &runtime, ns, Some(destination.canonical))?;
            tree.redundant_overrides = redundant;
            files
        }
    };
    for file in files {
        tree.insert(&file.relative_path, file.content, file.executable);
    }
    Ok(tree)
}

/// A call at `canonical`, written in `runtime`'s syntax, a skill of a plugin
/// named by `naming`.
fn render_call(
    call: &Call,
    canonical: &str,
    runtime: Option<RuntimeId>,
    naming: SkillNaming,
) -> Result<String, CoreError> {
    call.check_shipped(targets_name(call.targets.as_deref(), canonical), canonical)?;
    let Some(runtime) = runtime else {
        return Ok(call.skill.name.clone());
    };
    match &call.skill.plugin {
        Some(plugin) => {
            crate::export::rendered_skill_call(runtime, naming, plugin, &call.skill.name)
        }
        None => crate::export::checked_skill_call(runtime, None, &call.skill.name),
    }
}

/// How a harness names a published skill; [`SkillNaming::Bare`] for a row
/// with no plugin format, where no skill has a plugin.
fn naming(profile: &HarnessProfile) -> SkillNaming {
    profile
        .plugin
        .as_ref()
        .map_or(SkillNaming::Bare, |f| f.naming)
}

/// A body's segments as text: each call through `call`, each link as its
/// markdown, and each CLI call site as `cli` says.
fn write_body(
    body: &Body,
    cli: CliInvocation,
    call: impl Fn(&Call) -> Result<String, CoreError>,
) -> Result<(String, bool), CoreError> {
    let mut out = String::new();
    let mut used_shim = false;
    for segment in &body.0 {
        match segment {
            Segment::Text { text } => out.push_str(text),
            Segment::Link { target } => out.push_str(&target.markdown()),
            Segment::Call { call: site } => out.push_str(&call(site)?),
            Segment::CliInvocation { shim_target } => match cli {
                CliInvocation::PluginRootToken => {
                    out.push_str("${CLAUDE_PLUGIN_ROOT}/");
                    out.push_str(shim_target);
                }
                CliInvocation::SkillRelativeShim => {
                    out.push_str(SHIM_RELATIVE_PATH);
                    used_shim = true;
                }
            },
        }
    }
    Ok((out, used_shim))
}

/// A resolved component as a projection: its content, its body and
/// resources written through `body`, its extensions carried for the renderer
/// to apply. Returns whether the entry body used the shim.
fn projection_of(
    component: &Component,
    body: impl Fn(&Body) -> Result<(String, bool), CoreError>,
) -> Result<(SkillProjection, bool), CoreError> {
    let resolved = component
        .resolved
        .as_ref()
        .expect("a component is resolved before it is written");
    let mut content = component
        .content
        .clone()
        .expect("a resolved component was read");
    let (text, used_shim) = body(&resolved.body)?;
    content.body = text;
    content.apply_overrides(component.extensions.blocks.clone());
    let mut resources = Vec::with_capacity(resolved.resources.len());
    for resource in &resolved.resources {
        let bytes = match &resource.content {
            ResourceContent::Body { body: file } => body(file)?.0.into_bytes(),
            ResourceContent::Bytes { bytes } => bytes.clone(),
        };
        resources.push((resource.path.clone(), bytes, resource.executable));
    }
    Ok((SkillProjection { content, resources }, used_shim))
}

/// The provenance marker, after the body is written so the validator has
/// already ruled on what it annotates. A comment, so every harness ignores
/// it.
fn mark_generated(projection: &mut SkillProjection, path: &str) {
    projection.content.body = format!(
        "{GENERATED_MARKER}{path}; do not edit. -->\n\n{}",
        projection.content.body
    );
}

/// Rewrites `${CLAUDE_PLUGIN_ROOT}/skills/<name>` to
/// `${CLAUDE_PLUGIN_ROOT}/skills/<plugin>-<name>` for each `<name>` in
/// `siblings`, so a body that addresses a skill's files through the plugin
/// root still finds them under [`SkillNaming::PluginPrefixed`]. Any other
/// name, and any `skills/` path not after the token, is left alone.
pub(crate) fn rewrite_sibling_paths(body: &str, plugin: &str, siblings: &BTreeSet<&str>) -> String {
    const NEEDLE: &str = "${CLAUDE_PLUGIN_ROOT}/skills/";
    let mut out = String::with_capacity(body.len());
    let mut rest = body;
    while let Some(offset) = rest.find(NEEDLE) {
        let (head, tail) = rest.split_at(offset + NEEDLE.len());
        out.push_str(head);
        let end = tail
            .find(|c: char| !(c.is_ascii_alphanumeric() || matches!(c, '-' | '_')))
            .unwrap_or(tail.len());
        if siblings.contains(&tail[..end]) {
            out.push_str(plugin);
            out.push('-');
        }
        rest = tail;
    }
    out.push_str(rest);
    out
}

/// A body's `${CLAUDE_PLUGIN_ROOT}/<shim_target>` call sites rewritten to the
/// skill-relative shim, and whether there were any — the load's split and a
/// [`CliInvocation::SkillRelativeShim`] harness's writing, end to end.
#[cfg(test)]
pub(crate) fn rewrite_cli_invocation(body: &str, shim_target: &str) -> (String, bool) {
    let body = crate::model::segments(body, &Default::default(), Some(shim_target));
    write_body(&body, CliInvocation::SkillRelativeShim, |_| unreachable!())
        .expect("a body with no calls writes")
}

/// The per-skill `scripts/sdlc` shim: a parent-walk from its own directory
/// looking for `shim_target` — the plugin-level launcher asset, from
/// [`MarketplaceConfig::shim_target`] — falling back to `sdlc` on `PATH`.
/// POSIX `sh`, not `bash`: the plugin's own `cli/sdlc` launcher is the one
/// script here that already commits to bash (it needs `BASH_SOURCE` to
/// resolve a symlink chain); this one does not need that, so it stays to the
/// smaller shell.
fn sdlc_shim_script(shim_target: &str) -> String {
    format!(
        "#!/bin/sh\n\
# sdlc — per-skill shim. GENERATED by skillwright; do not edit.\n\
#\n\
# Walks up from this script's own directory looking for {shim_target} — the\n\
# plugin-level launcher asset — and runs it. Falls back to `sdlc` on PATH\n\
# when no such ancestor is found (a skill copied out of the plugin, or a\n\
# harness that doesn't lay out {shim_target} where this build put it).\n\
#\n\
# This skill's own body calls this shim directly: its harness has no\n\
# `${{CLAUDE_PLUGIN_ROOT}}` substitution of its own, so every\n\
# `${{CLAUDE_PLUGIN_ROOT}}/{shim_target}` call site the vault wrote was\n\
# rewritten to this skill-relative path at render time. Claude Code does\n\
# substitute that token, so a Claude skill never gets this file at all.\n\
set -eu\n\
\n\
dir=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\n\
while [ \"$dir\" != \"/\" ]; do\n\
  if [ -x \"$dir/{shim_target}\" ]; then\n\
    exec \"$dir/{shim_target}\" \"$@\"\n\
  fi\n\
  dir=$(dirname -- \"$dir\")\n\
done\n\
\n\
exec sdlc \"$@\"\n\
"
    )
}

/// [`HarnessTranslator::hooks`]'s shared body: every hook note projected,
/// plus the hooks from the plugin's canonical file this harness carries,
/// each localized ([`crate::hooks_file::localize`]; notes are not), written
/// as the single `hooks/hooks.json` the plugin format defines.
///
/// A hook is not a file: a harness reads one hooks document per plugin, so
/// the members render together or the second one overwrites the first. No
/// provenance marker, and no transclusion — the body is a script or a prompt
/// inside a JSON string, and a comment or an embed would change what runs.
fn default_hooks(
    profile: &HarnessProfile,
    plugin: &Plugin,
    hooks: &[&Component],
    base: &str,
    tree: &mut FileTree,
) -> Result<bool, CoreError> {
    let runtime = parse_runtime_target(profile.runtime)?;
    let mut rendered = Vec::with_capacity(hooks.len());
    for hook in hooks {
        let projection = SkillProjection {
            content: hook.content.clone().expect("an admitted hook was read"),
            resources: hook.source.clone().unwrap_or_default(),
        };
        let adapted = to_adapt_hook(&projection, Some(profile.name))?;
        if hook.targets.is_none()
            && agent_adapt::render::hook_refusal(&adapted, runtime).is_some()
            && carried_elsewhere(&projection, profile)?
        {
            continue;
        }
        rendered.push(adapted);
    }
    if let Some(file) = &plugin.hooks_file {
        tree.insert(
            &format!("{base}/{}", crate::hooks_file::GAP_REPORT_PATH),
            file.gap_report.clone().into_bytes(),
            false,
        );
        if profile.format().carries_hooks {
            let var = profile.format().plugin_root_var.map(|var| var.name);
            rendered.extend(
                crate::hooks_file::carried_hooks(&file.hooks, runtime)
                    .into_iter()
                    .map(|hook| crate::hooks_file::localize(hook, profile.name, var)),
            );
        }
    }
    let Some(bytes) = project_plugin_hooks(&rendered, profile.runtime)? else {
        return Ok(false);
    };
    tree.insert(&format!("{base}/{PLUGIN_HOOKS_PATH}"), bytes, false);
    Ok(true)
}

/// Does some hooks-carrying harness other than `profile` carry this hook
/// note? Every harness counts, selected or not, so the answer does not depend
/// on what a build selects.
fn carried_elsewhere(
    projection: &SkillProjection,
    profile: &HarnessProfile,
) -> Result<bool, CoreError> {
    for other in super::with_plugin_format() {
        if other.name == profile.name || !other.format().carries_hooks {
            continue;
        }
        let hook = to_adapt_hook(projection, Some(other.name))?;
        let runtime = parse_runtime_target(other.runtime)?;
        if agent_adapt::render::hook_refusal(&hook, runtime).is_none() {
            return Ok(true);
        }
    }
    Ok(false)
}

