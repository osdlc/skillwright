/// The provenance marker every `SKILL.md` and command a built marketplace
/// emits opens its body with. `check` reads it back to tell a tree this tool
/// built from one somebody wrote.
pub const GENERATED_MARKER: &str = "<!-- Generated by skillwright from ";

/// What a translator returns: every file, by path.
#[derive(Debug, Clone, Default, PartialEq)]
pub(crate) struct FileTree {
    /// Forward-slashed paths, relative to the directory the tree is emitted
    /// into, to their content.
    pub files: BTreeMap<String, PreviewWrite>,
}

impl FileTree {
    /// Adds a file, replacing one already at `path` — the order a pack is
    /// written in decides, the same as writes landing on one directory.
    pub fn insert(&mut self, path: &str, bytes: Vec<u8>, executable: bool) {
        self.files.insert(
            crate::skill::forward_slashed(Path::new(path)),
            PreviewWrite { bytes, executable },
        );
    }
}

/// One harness's way of writing the marketplace model.
#[derive(Debug, Clone, Copy)]
pub(crate) struct Translator(pub Harness);

impl Translator {
    /// The harness's row.
    fn profile(self) -> &'static HarnessProfile {
        self.0.profile()
    }

    /// The harness's plugin format.
    fn format(self) -> &'static PluginFormat {
        self.0.format()
    }

    /// Does this pack carry this member? Its kind has a place in the pack.
    pub(crate) fn admits(self, component: &Component) -> bool {
        self.format().carries(component.kind)
    }

    /// The name a skill of `plugin` publishes under: its directory, its
    /// frontmatter `name`, and the name a call to it renders.
    ///
    /// # Errors
    ///
    /// `refused: published-name-invalid` — a prefixed name the Agent Skills
    /// spec does not admit.
    fn published_name(self, plugin: &Plugin, skill: &str) -> Result<String, CoreError> {
        let naming = naming(self.0, &plugin.bare_on);
        crate::export::published_skill_name(naming, &plugin.name, skill)
    }

    /// A call, as this harness invokes the skill it names.
    ///
    /// # Errors
    ///
    /// `refused: skill-call-not-shipped` when this harness does not ship the
    /// skill, and what the runtime refuses about the name.
    fn render_call(self, call: &Call) -> Result<String, CoreError> {
        let profile = self.profile();
        call.check_shipped(self.format().carries(call.skill.kind), profile.label)?;
        crate::export::rendered_skill_call(
            profile.runtime,
            naming(self.0, &call.bare_on),
            &call.skill.plugin,
            &call.skill.name,
        )
    }

    /// A link of `plugin`, written from where its text lands in this
    /// harness's pack to where its file lands.
    ///
    /// # Errors
    ///
    /// `refused: link-not-shipped` when this harness's pack does not contain
    /// the component the link reaches into (spec section 4 rule 6), and what
    /// naming a skill refuses.
    fn render_link(self, plugin: &Plugin, link: &ResolvedRef) -> Result<String, CoreError> {
        if let Some(component) = &link.component {
            let members = match component.kind {
                EntityKind::Skill => plugin.skills.as_slice(),
                EntityKind::Command => plugin.commands.as_slice(),
                _ => &[],
            };
            let carried = members
                .iter()
                .find(|member| member.name == component.name)
                .is_some_and(|member| self.admits(member));
            if !carried {
                return Err(CoreError::refused(
                    refusal::LINK_NOT_SHIPPED,
                    format!(
                        "{}: `{}` links to {} `{}`, which the {} pack does not contain \
                         (section 4 rule 6)",
                        link.caller,
                        link.written,
                        component.kind.as_str(),
                        component.name,
                        self.profile().label
                    ),
                ));
            }
        }
        let from = self.installed(plugin, &link.from)?;
        let to = self.installed(plugin, &link.to)?;
        Ok(link.markdown_at(&from, &to))
    }

    /// A path in a pack laid out as Claude Code's, `skills/<s>/…`, moved to
    /// this harness's folder for skill `<s>`.
    ///
    /// # Errors
    ///
    /// What [`Self::published_name`] refuses.
    fn installed(self, plugin: &Plugin, path: &str) -> Result<String, CoreError> {
        match path
            .strip_prefix("skills/")
            .and_then(|rest| rest.split_once('/'))
        {
            Some((skill, rest)) => Ok(format!(
                "skills/{}/{rest}",
                self.published_name(plugin, skill)?
            )),
            None => Ok(path.to_owned()),
        }
    }

    /// Every file this harness's pack of `plugin` ships, at its path in a
    /// pack laid out as Claude Code's.
    fn shipped(self, plugin: &Plugin) -> BTreeSet<String> {
        let mut out: BTreeSet<String> = plugin.assets.iter().map(|a| a.dest.clone()).collect();
        out.extend(plugin.references.iter().map(|r| r.path.clone()));
        for skill in plugin.skills.iter().filter(|c| self.admits(c)) {
            let base = format!("skills/{}", skill.name);
            out.insert(format!("{base}/SKILL.md"));
            if let Some(resolved) = &skill.resolved {
                out.extend(
                    resolved
                        .resources
                        .iter()
                        .map(|r| format!("{base}/{}", r.path)),
                );
            }
        }
        for command in plugin.commands.iter().filter(|c| self.admits(c)) {
            out.insert(format!("commands/{}.md", command.name));
        }
        if self.format().policy.carries_hooks && plugin.hooks_file.is_some() {
            out.insert(PLUGIN_HOOKS_PATH.to_owned());
        }
        out
    }

    /// A `${PLUGIN_ROOT}/<path>` of `plugin`, as this harness writes it
    /// (spec section 4 rules 18 and 19). `shipped` is [`Self::shipped`].
    ///
    /// # Errors
    ///
    /// `refused: plugin-root-not-shipped` when the pack does not ship the
    /// file (rules 17 and 20), and what naming a skill refuses.
    fn render_plugin_root(
        self,
        plugin: &Plugin,
        shipped: &BTreeSet<String>,
        root: &PluginRootPath,
    ) -> Result<String, CoreError> {
        if !shipped.contains(&root.path) {
            return Err(crate::hooks_file::not_shipped(
                &root.caller,
                &root.written,
                &root.path,
                self.profile().label,
            ));
        }
        match self.format().policy.cli_invocation {
            CliInvocation::PluginRootToken => {
                Ok(format!("{}/{}", crate::hooks_file::CLAUDE_ROOT, root.path))
            }
            CliInvocation::SkillRelativePath => Ok(relative_path(
                &self.installed(plugin, &root.from)?,
                &self.installed(plugin, &root.path)?,
            )),
        }
    }

    /// A resolved body of `plugin` as this harness reads it.
    ///
    /// # Errors
    ///
    /// What [`Self::render_call`], [`Self::render_link`] and
    /// [`Self::render_plugin_root`] refuse.
    fn render_body(self, plugin: &Plugin, body: &Body) -> Result<String, CoreError> {
        let shipped = std::cell::OnceCell::new();
        write_body(
            body,
            |call| self.render_call(call),
            |link| self.render_link(plugin, link),
            |root| {
                let shipped = shipped.get_or_init(|| self.shipped(plugin));
                self.render_plugin_root(plugin, shipped, root)
            },
        )
    }

    /// The plugin's hooks file, written into `tree` under `base`.
    ///
    /// A hook this harness cannot carry is left out, not refused.
    ///
    /// # Errors
    ///
    /// `refused: plugin-root-not-shipped` for a hook's path to a file the
    /// pack does not ship, and what [`project_plugin_hooks`] refuses.
    fn hooks(self, plugin: &Plugin, base: &str, tree: &mut FileTree) -> Result<(), CoreError> {
        let Some(file) = &plugin.hooks_file else {
            return Ok(());
        };
        let (profile, format) = (self.profile(), self.format());
        if !format.policy.carries_hooks {
            return Ok(());
        }
        let shipped = self.shipped(plugin);
        let var = format.plugin_root_var.map(|var| var.name);
        let carried = crate::hooks_file::carried_hooks(&file.hooks, profile.runtime);
        crate::hooks_file::check_hook_paths(&carried, &file.path, profile.label, |path| {
            shipped.contains(path)
        })?;
        let rendered: Vec<_> = carried
            .into_iter()
            .map(|hook| crate::hooks_file::localize(hook, self.0.as_str(), var))
            .collect();
        let Some(bytes) = project_plugin_hooks(&rendered, profile.runtime)? else {
            return Ok(());
        };
        tree.insert(&format!("{base}/{PLUGIN_HOOKS_PATH}"), bytes, false);
        Ok(())
    }

    /// The marketplace manifest listing `listed` — each carried plugin and
    /// its carried skills' names. `None` for a harness with no marketplace.
    fn marketplace_manifest(
        self,
        listed: &[(&str, Vec<&str>)],
        name: &str,
        config: &MarketplaceConfig,
    ) -> Option<String> {
        let build = match self.0 {
            Harness::Claude => claude_marketplace_manifest,
            Harness::Codex => codex_marketplace_manifest,
            Harness::Cursor => cursor_marketplace_manifest,
            Harness::Pi => return None,
        };
        Some(build(listed, self.format().policy.packs, name, config))
    }

    /// The whole marketplace as this harness's tree, paths relative to the
    /// marketplace directory.
    ///
    /// # Errors
    ///
    /// What writing any member refuses.
    pub(crate) fn translate(self, market: &Marketplace) -> Result<FileTree, CoreError> {
        let format = self.format();
        self.refuse_name_collisions(market)?;
        let mut tree = FileTree::default();
        let mut listed: Vec<(&str, Vec<&str>)> = Vec::new();
        for (name, plugin) in &market.plugins {
            let Some(skills) = self.write_pack(
                plugin,
                &market.config,
                &format!("{}/{name}", format.policy.packs),
                &mut tree,
            )?
            else {
                continue;
            };
            listed.push((name, skills));
        }
        if let Some(path) = format.marketplace_manifest
            && let Some(manifest) = self.marketplace_manifest(&listed, &market.name, &market.config)
        {
            tree.insert(path, manifest.into_bytes(), false);
        }
        Ok(tree)
    }

    /// One plugin's pack into `tree` under `base`: its skills, its commands
    /// where the pack has a place for one, its hooks, its assets and its
    /// manifest. Returns the carried skills' names, or `None` when this
    /// harness carries nothing of the plugin — a plugin whose every member's
    /// kind this pack has no place for is absent entirely: no directory, no
    /// manifest, no listing. A plugin with no member is carried, as its
    /// manifest alone, by every harness built.
    ///
    /// # Errors
    ///
    /// What writing any member refuses.
    fn write_pack<'p>(
        self,
        plugin: &'p Plugin,
        config: &MarketplaceConfig,
        base: &str,
        tree: &mut FileTree,
    ) -> Result<Option<Vec<&'p str>>, CoreError> {
        let skills: Vec<&Component> = plugin.skills.iter().filter(|c| self.admits(c)).collect();
        let commands: Vec<&Component> = plugin.commands.iter().filter(|c| self.admits(c)).collect();
        if !plugin.carried_by(|c| self.admits(c)) {
            return Ok(None);
        }
        for skill in &skills {
            self.write_pack_skill(plugin, skill, base, tree)?;
        }
        for command in &commands {
            self.write_pack_command(plugin, command, base, tree)?;
        }
        for reference in &plugin.references {
            let bytes = match &reference.content {
                ResourceContent::Body { body } => self.render_body(plugin, body)?.into_bytes(),
                ResourceContent::Bytes { bytes } => bytes.clone(),
            };
            tree.insert(
                &format!("{base}/{}", reference.path),
                bytes,
                reference.executable,
            );
        }
        self.hooks(plugin, base, tree)?;
        for asset in &plugin.assets {
            tree.insert(
                &format!("{base}/{}", asset.dest),
                asset.bytes.clone(),
                asset.executable,
            );
        }
        let names: Vec<&str> = skills.iter().map(|s| s.name.as_str()).collect();
        let manifest = render_plugin_manifest(self.0, &plugin.name, &names, config);
        tree.insert(
            &format!("{base}/{}", self.format().plugin_manifest),
            manifest.into_bytes(),
            false,
        );
        Ok(Some(names))
    }

    /// One skill into a pack, at `<base>/skills/<published name>/`.
    ///
    /// # Errors
    ///
    /// `refused: published-name-invalid`, and what rendering refuses.
    fn write_pack_skill(
        self,
        plugin: &Plugin,
        skill: &Component,
        base: &str,
        tree: &mut FileTree,
    ) -> Result<(), CoreError> {
        let profile = self.profile();
        let format = self.format();
        let published = self.published_name(plugin, &skill.name)?;
        let mut projection = projection_of(skill, |body| self.render_body(plugin, body))?;
        projection.content.name = published.clone();
        mark_generated(&mut projection, &skill.path);
        let files = project_skill(&projection, self.0)?;
        let strip = format!("{}/{published}/", format.skills_dir);
        for file in files {
            let relative = file.relative_path.strip_prefix(&strip).ok_or_else(|| {
                CoreError::Projection(format!(
                    "{}: `{}` did not land under `{strip}` — the {} projection moved its layout",
                    skill.name,
                    file.relative_path,
                    profile.runtime.as_str()
                ))
            })?;
            tree.insert(
                &format!("{base}/skills/{published}/{relative}"),
                file.content,
                file.executable,
            );
        }
        Ok(())
    }

    /// One command into a pack, at `<base>/commands/<name>.<ext>`. Called
    /// only where the pack has a place for one.
    ///
    /// # Errors
    ///
    /// What rendering refuses.
    fn write_pack_command(
        self,
        plugin: &Plugin,
        command: &Component,
        base: &str,
        tree: &mut FileTree,
    ) -> Result<(), CoreError> {
        let profile = self.profile();
        let mut projection = projection_of(command, |body| self.render_body(plugin, body))?;
        mark_generated(&mut projection, &command.path);
        // A command projects to exactly one file, so the file's own name is
        // all that travels onto `commands/`.
        let files = project_command(&projection, self.0)?;
        for file in files {
            let filename = Path::new(&file.relative_path).file_name().ok_or_else(|| {
                CoreError::Projection(format!(
                    "{}: `{}` names no file — the {} projection moved its layout",
                    command.name,
                    file.relative_path,
                    profile.runtime.as_str()
                ))
            })?;
            tree.insert(
                &format!("{base}/commands/{}", filename.to_string_lossy()),
                file.content,
                file.executable,
            );
        }
        Ok(())
    }

    /// Refuses two skills of different plugins that publish under one name
    /// on a harness with no plugin namespace (spec section 8 rule 6).
    ///
    /// `<plugin>-<skill>` is not injective (`a` + `b-c` and `a-b` + `c` are
    /// both `a-b-c`), a plugin's prefixed name can meet another plugin's bare
    /// one, and two bare names can be equal. The load refuses a collision
    /// inside one plugin; this refuses one across plugins.
    ///
    /// # Errors
    ///
    /// `refused: path-collision`, and what [`Self::published_name`] refuses.
    fn refuse_name_collisions(self, market: &Marketplace) -> Result<(), CoreError> {
        if self.format().naming == SkillNaming::HostNamespaced {
            return Ok(());
        }
        let mut published: BTreeMap<String, (&Plugin, &Component)> = BTreeMap::new();
        for group in market.plugins.values() {
            for skill in group.skills.iter().filter(|c| self.admits(c)) {
                let name = self.published_name(group, &skill.name)?;
                let Some((first_group, first)) = published.get(&name).copied() else {
                    published.insert(name, (group, skill));
                    continue;
                };
                let why = collision_reason(self.0, [group, first_group]);
                return Err(CoreError::refused(
                    refusal::PATH_COLLISION,
                    format!(
                        "`{}` (plugin `{}`) and `{}` (plugin `{}`) both publish as {} skill \
                         `{name}`: {why}",
                        first.path,
                        first_group.name,
                        skill.path,
                        group.name,
                        self.profile().label
                    ),
                ));
            }
        }
        Ok(())
    }
}

/// How `harness` names a published skill of a plugin that is bare on the
/// harnesses in `bare_on`, or else its default.
fn naming(harness: Harness, bare_on: &[Harness]) -> SkillNaming {
    if bare_on.contains(&harness) {
        return SkillNaming::Bare;
    }
    harness.format().naming
}

/// A body's segments as text: each call through `call`, each link through
/// `link`, each plugin-root path through `root`.
fn write_body(
    body: &Body,
    call: impl Fn(&Call) -> Result<String, CoreError>,
    link: impl Fn(&ResolvedRef) -> Result<String, CoreError>,
    root: impl Fn(&PluginRootPath) -> Result<String, CoreError>,
) -> Result<String, CoreError> {
    let mut out = String::new();
    for segment in &body.segments {
        match segment {
            Segment::Text { text } | Segment::Literal { text } => out.push_str(text),
            Segment::Link { target } => out.push_str(&link(target)?),
            Segment::Call { call: site } => out.push_str(&call(site)?),
            Segment::PluginRoot { path } => out.push_str(&root(path)?),
        }
    }
    Ok(out)
}

/// The path from the folder of the file `from` to `to`, both `/`-separated
/// and relative to one root. A file's path to itself is its name.
pub(crate) fn relative_path(from: &str, to: &str) -> String {
    let from: Vec<&str> = from.split('/').filter(|s| !s.is_empty()).collect();
    let folder = &from[..from.len().saturating_sub(1)];
    let to: Vec<&str> = to.split('/').filter(|s| !s.is_empty()).collect();
    let shared = folder.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut out: Vec<&str> = vec![".."; folder.len() - shared];
    out.extend(&to[shared..]);
    if out.is_empty() {
        return to.last().copied().unwrap_or_default().to_owned();
    }
    out.join("/")
}

/// Why two skills of one published name on `harness` are refused: both
/// names bare through `naming: bare`, or the harness's prefixing default.
fn collision_reason(harness: Harness, plugins: [&Plugin; 2]) -> String {
    let label = harness.profile().label;
    let bare = plugins
        .into_iter()
        .all(|g| naming(harness, &g.bare_on) == SkillNaming::Bare);
    if bare {
        format!(
            "`{harness}.naming: bare` names both bare, and {label} has no plugin namespace, \
             so no two skills may take one name. Rename one"
        )
    } else {
        format!(
            "{label} has no plugin namespace and names a skill `<plugin>-<skill>` unless \
             `{harness}.naming: bare` is set, so no two skills may take one name. Rename one"
        )
    }
}

/// A resolved component as a projection: its content, its body and
/// resources written through `body`, its extensions carried for the renderer
/// to apply.
fn projection_of(
    component: &Component,
    body: impl Fn(&Body) -> Result<String, CoreError>,
) -> Result<SkillProjection, CoreError> {
    let resolved = component
        .resolved
        .as_ref()
        .expect("a component is resolved before it is written");
    let mut content = resolved.content.clone();
    let text = body(&resolved.body)?;
    content.body = text;
    content.apply_overrides(component.extensions.blocks.clone());
    let mut resources = Vec::with_capacity(resolved.resources.len());
    for resource in &resolved.resources {
        let bytes = match &resource.content {
            ResourceContent::Body { body: file } => body(file)?.into_bytes(),
            ResourceContent::Bytes { bytes } => bytes.clone(),
        };
        resources.push((resource.path.clone(), bytes, resource.executable));
    }
    Ok(SkillProjection { content, resources })
}

/// The provenance marker, after the body is written so the validator has
/// already ruled on what it annotates. A comment, so every harness ignores
/// it.
fn mark_generated(projection: &mut SkillProjection, path: &str) {
    projection.content.body = format!(
        "{GENERATED_MARKER}{path}; do not edit. -->\n\n{}",
        projection.content.body
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn naming_reads_the_bare_list_then_the_default() {
        for (harness, default) in [
            (Harness::Claude, SkillNaming::HostNamespaced),
            (Harness::Codex, SkillNaming::HostNamespaced),
            (Harness::Cursor, SkillNaming::PluginPrefixed),
            (Harness::Pi, SkillNaming::PluginPrefixed),
        ] {
            assert_eq!(naming(harness, &[]), default, "{harness}");
            assert_eq!(naming(harness, &[harness]), SkillNaming::Bare, "{harness}");
            let other = Harness::ALL.into_iter().find(|h| *h != harness).unwrap();
            assert_eq!(naming(harness, &[other]), default, "{harness}");
        }
    }

    #[test]
    fn a_host_namespaced_harness_writes_the_plugin_into_every_call() {
        // A build spells calls from the profile's naming. It must agree with
        // the runtime's own `namespaced` flag, or a call would not match how
        // the runtime names the skill.
        for harness in Harness::ALL {
            let namespaced = harness.profile().runtime.skill_call_syntax().namespaced;
            if harness.format().naming == SkillNaming::HostNamespaced {
                assert!(namespaced, "{harness}");
            }
        }
    }
}
